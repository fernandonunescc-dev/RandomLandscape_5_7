#include "MarchingCubes.h"

// ----------------------------------------------------------------
// Edge interpolation
// ----------------------------------------------------------------
FVector FMarchingCubes::InterpolateEdge(
	const FVector& P1, const FVector& P2,
	float V1, float V2, float IsoLevel)
{
	if (FMath::Abs(IsoLevel - V1) < KINDA_SMALL_NUMBER) return P1;
	if (FMath::Abs(IsoLevel - V2) < KINDA_SMALL_NUMBER) return P2;
	if (FMath::Abs(V1 - V2) < KINDA_SMALL_NUMBER) return P1;

	const float T = (IsoLevel - V1) / (V2 - V1);
	return P1 + T * (P2 - P1);
}

// ----------------------------------------------------------------
// Mesh extraction
// ----------------------------------------------------------------
void FMarchingCubes::Extract(const FVoxelChunk& Chunk, float VoxelSize, float IsoLevel, FMeshData& OutMesh)
{
	OutMesh.Vertices.Reset();
	OutMesh.Triangles.Reset();
	OutMesh.Normals.Reset();
	OutMesh.UVs.Reset();
	OutMesh.VertexColors.Reset();

	if (Chunk.bIsEmpty || Chunk.bIsSolid)
	{
		return; // No surface to extract
	}

	const int32 Res = Chunk.Resolution;
	if (Res < 2) return;

	// World offset for this chunk
	const FVector ChunkOrigin(
		static_cast<float>(Chunk.ChunkCoord.X) * Res * VoxelSize,
		static_cast<float>(Chunk.ChunkCoord.Y) * Res * VoxelSize,
		static_cast<float>(Chunk.ChunkCoord.Z) * Res * VoxelSize);

	// Iterate over all cubes (each cube is 2×2×2 corner samples).
	// Thanks to the (Res+1)³ padded density storage, we iterate the full Res cubes
	// per axis, eliminating 1-voxel seams between chunks.
	for (int32 Z = 0; Z < Res; ++Z)
	{
		for (int32 Y = 0; Y < Res; ++Y)
		{
			for (int32 X = 0; X < Res; ++X)
			{
				// 8 corner positions and density values
				FVector Corners[8];
				float Values[8];

				// Corner ordering (standard MC convention):
				// 0: (X,   Y,   Z  )   4: (X,   Y,   Z+1)
				// 1: (X+1, Y,   Z  )   5: (X+1, Y,   Z+1)
				// 2: (X+1, Y+1, Z  )   6: (X+1, Y+1, Z+1)
				// 3: (X,   Y+1, Z  )   7: (X,   Y+1, Z+1)

				const int32 CX[8] = { X, X+1, X+1, X,   X,   X+1, X+1, X   };
				const int32 CY[8] = { Y, Y,   Y+1, Y+1, Y,   Y,   Y+1, Y+1 };
				const int32 CZ[8] = { Z, Z,   Z,   Z,   Z+1, Z+1, Z+1, Z+1 };

				for (int32 i = 0; i < 8; ++i)
				{
					Corners[i] = ChunkOrigin + FVector(
						static_cast<float>(CX[i]) * VoxelSize,
						static_cast<float>(CY[i]) * VoxelSize,
						static_cast<float>(CZ[i]) * VoxelSize);
					Values[i] = Chunk.Density[Chunk.Index(CX[i], CY[i], CZ[i])];
				}

				// Determine cube configuration index
				int32 CubeIndex = 0;
				for (int32 i = 0; i < 8; ++i)
				{
					if (Values[i] > IsoLevel)
					{
						CubeIndex |= (1 << i);
					}
				}

				// Skip if cube is entirely inside or outside
				if (EdgeTable[CubeIndex] == 0) continue;

				// Interpolate vertices along active edges
				FVector EdgeVerts[12];

				if (EdgeTable[CubeIndex] & 1)    EdgeVerts[0]  = InterpolateEdge(Corners[0], Corners[1], Values[0], Values[1], IsoLevel);
				if (EdgeTable[CubeIndex] & 2)    EdgeVerts[1]  = InterpolateEdge(Corners[1], Corners[2], Values[1], Values[2], IsoLevel);
				if (EdgeTable[CubeIndex] & 4)    EdgeVerts[2]  = InterpolateEdge(Corners[2], Corners[3], Values[2], Values[3], IsoLevel);
				if (EdgeTable[CubeIndex] & 8)    EdgeVerts[3]  = InterpolateEdge(Corners[3], Corners[0], Values[3], Values[0], IsoLevel);
				if (EdgeTable[CubeIndex] & 16)   EdgeVerts[4]  = InterpolateEdge(Corners[4], Corners[5], Values[4], Values[5], IsoLevel);
				if (EdgeTable[CubeIndex] & 32)   EdgeVerts[5]  = InterpolateEdge(Corners[5], Corners[6], Values[5], Values[6], IsoLevel);
				if (EdgeTable[CubeIndex] & 64)   EdgeVerts[6]  = InterpolateEdge(Corners[6], Corners[7], Values[6], Values[7], IsoLevel);
				if (EdgeTable[CubeIndex] & 128)  EdgeVerts[7]  = InterpolateEdge(Corners[7], Corners[4], Values[7], Values[4], IsoLevel);
				if (EdgeTable[CubeIndex] & 256)  EdgeVerts[8]  = InterpolateEdge(Corners[0], Corners[4], Values[0], Values[4], IsoLevel);
				if (EdgeTable[CubeIndex] & 512)  EdgeVerts[9]  = InterpolateEdge(Corners[1], Corners[5], Values[1], Values[5], IsoLevel);
				if (EdgeTable[CubeIndex] & 1024) EdgeVerts[10] = InterpolateEdge(Corners[2], Corners[6], Values[2], Values[6], IsoLevel);
				if (EdgeTable[CubeIndex] & 2048) EdgeVerts[11] = InterpolateEdge(Corners[3], Corners[7], Values[3], Values[7], IsoLevel);

				// Determine material color from the dominant solid corner
				FColor VoxColor(128, 128, 128, 255);
				float MaxDensity = -FLT_MAX;
				int32 DominantCorner = 0;
				for (int32 i = 0; i < 8; ++i)
				{
					if (Values[i] > MaxDensity)
					{
						MaxDensity = Values[i];
						DominantCorner = i;
					}
				}

				const EVoxelMaterial Mat = static_cast<EVoxelMaterial>(
					Chunk.Materials[Chunk.Index(CX[DominantCorner], CY[DominantCorner], CZ[DominantCorner])]);

				switch (Mat)
				{
				case EVoxelMaterial::Grass:   VoxColor = FColor(80, 160, 60, 255);  break;
				case EVoxelMaterial::Dirt:    VoxColor = FColor(140, 100, 60, 255);  break;
				case EVoxelMaterial::Stone:   VoxColor = FColor(130, 130, 130, 255); break;
				case EVoxelMaterial::Sand:    VoxColor = FColor(210, 200, 140, 255); break;
				case EVoxelMaterial::Snow:    VoxColor = FColor(240, 245, 255, 255); break;
				case EVoxelMaterial::Ice:     VoxColor = FColor(180, 220, 255, 255); break;
				case EVoxelMaterial::Water:   VoxColor = FColor(30, 80, 200, 255);   break;
				case EVoxelMaterial::Lava:    VoxColor = FColor(255, 80, 20, 255);   break;
				case EVoxelMaterial::Bedrock: VoxColor = FColor(50, 50, 50, 255);    break;
				default: break;
				}

				// Emit triangles using standard MC table winding (CCW from outside the solid).
				// UE5's ProceduralMeshComponent treats CCW as front-facing, so standard
				// winding produces correct outward-facing normals without any swap.
				for (int32 i = 0; TriTable[CubeIndex][i] != -1; i += 3)
				{
					const int32 BaseVertex = OutMesh.Vertices.Num();

					for (int32 j = 0; j < 3; ++j)
					{
						const FVector& V = EdgeVerts[TriTable[CubeIndex][i + j]];
						OutMesh.Vertices.Add(V);
						OutMesh.VertexColors.Add(VoxColor);

						// Simple planar UV projection
						OutMesh.UVs.Add(FVector2D(V.X / (VoxelSize * 32.0f), V.Y / (VoxelSize * 32.0f)));
					}

					OutMesh.Triangles.Add(BaseVertex);
					OutMesh.Triangles.Add(BaseVertex + 1);
					OutMesh.Triangles.Add(BaseVertex + 2);
				}
			}
		}
	}

	ComputeNormals(OutMesh);
}

// ----------------------------------------------------------------
// Compute smooth normals
// ----------------------------------------------------------------
void FMarchingCubes::ComputeNormals(FMeshData& Mesh)
{
	const int32 NumVerts = Mesh.Vertices.Num();
	const int32 NumTris = Mesh.Triangles.Num() / 3;

	Mesh.Normals.SetNumZeroed(NumVerts);

	for (int32 i = 0; i < NumTris; ++i)
	{
		const int32 I0 = Mesh.Triangles[i * 3 + 0];
		const int32 I1 = Mesh.Triangles[i * 3 + 1];
		const int32 I2 = Mesh.Triangles[i * 3 + 2];

		const FVector Edge1 = Mesh.Vertices[I1] - Mesh.Vertices[I0];
		const FVector Edge2 = Mesh.Vertices[I2] - Mesh.Vertices[I0];
		const FVector FaceNormal = FVector::CrossProduct(Edge1, Edge2);

		Mesh.Normals[I0] += FaceNormal;
		Mesh.Normals[I1] += FaceNormal;
		Mesh.Normals[I2] += FaceNormal;
	}

	for (int32 i = 0; i < NumVerts; ++i)
	{
		Mesh.Normals[i] = Mesh.Normals[i].GetSafeNormal();
	}
}

