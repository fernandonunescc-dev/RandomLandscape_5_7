#include "CaveGenerator.h"
#include "NoiseUtility.h"

//------------------------------------------------------------------------------
// Initialize
//------------------------------------------------------------------------------
void UCaveGenerator::Initialize(const FCaveSettings& InSettings, int32 GlobalSeed, int32 TextureResolution)
{
Settings = InSettings;
TerrainResolution = TextureResolution;

ActualSeed = (Settings.Seed != 0)
? Settings.Seed
: WorldNoise::DeriveSeed(GlobalSeed, 8);

UE_LOG(LogTemp, Log,
TEXT("CaveGenerator initialized – TerrainRes: %d, Seed: %d, Threshold: %.2f, Scale: %.1f, DepthLayers: %d, MaxDepth: %.0fm"),
TerrainResolution, ActualSeed, Settings.CaveThreshold, Settings.CaveScale, Settings.DepthLayers, Settings.MaxCaveDepthMeters);
}

//------------------------------------------------------------------------------
// Generate
//------------------------------------------------------------------------------
bool UCaveGenerator::Generate(const TArray<float>& FinalElevation, const TArray<uint8>& LandMask,
float WorldSizeCm, float MaxHeightCm)
{
if (TerrainResolution <= 0)
{
UE_LOG(LogTemp, Error, TEXT("CaveGenerator::Generate – not initialized"));
return false;
}

const int32 TotalPixels = TerrainResolution * TerrainResolution;
if (FinalElevation.Num() != TotalPixels || LandMask.Num() != TotalPixels)
{
UE_LOG(LogTemp, Error, TEXT("CaveGenerator::Generate – input size mismatch (expected %d)"), TotalPixels);
return false;
}

if (!Settings.bEnabled)
{
CaveMesh = FCaveMeshData();
CavePresenceMap.SetNumZeroed(TotalPixels);
UE_LOG(LogTemp, Log, TEXT("CaveGenerator::Generate – caves disabled, skipping"));
return true;
}

// Determine cave grid resolution
CaveResX = (Settings.CaveResolution > 0) ? Settings.CaveResolution : TerrainResolution;
CaveResY = CaveResX;
CaveResZ = Settings.DepthLayers;

UE_LOG(LogTemp, Log, TEXT("CaveGenerator::Generate – building density field %dx%dx%d"), CaveResX, CaveResY, CaveResZ);

BuildDensityField(FinalElevation, LandMask, WorldSizeCm, MaxHeightCm);
ExtractMeshMarchingCubes(WorldSizeCm, MaxHeightCm, FinalElevation);
BuildCavePresenceMap();

UE_LOG(LogTemp, Log, TEXT("CaveGenerator::Generate – complete: %d vertices, %d triangles"),
CaveMesh.Vertices.Num(), CaveMesh.Triangles.Num() / 3);

return true;
}

//------------------------------------------------------------------------------
// BuildDensityField
//------------------------------------------------------------------------------
void UCaveGenerator::BuildDensityField(const TArray<float>& FinalElevation, const TArray<uint8>& LandMask,
float WorldSizeCm, float MaxHeightCm)
{
const int32 TotalVoxels = CaveResX * CaveResY * CaveResZ;
DensityField.SetNumUninitialized(TotalVoxels);

const float MaxDepthCm = Settings.MaxCaveDepthMeters * 100.0f;
const float InvResX = 1.0f / static_cast<float>(CaveResX);
const float InvResY = 1.0f / static_cast<float>(CaveResY);
const float TerrainInvRes = 1.0f / static_cast<float>(TerrainResolution - 1);

for (int32 Y = 0; Y < CaveResY; ++Y)
{
for (int32 X = 0; X < CaveResX; ++X)
{
// Map cave grid to terrain grid
const float NormX = static_cast<float>(X) * InvResX;
const float NormY = static_cast<float>(Y) * InvResY;
const int32 TerrainX = FMath::Clamp(FMath::RoundToInt(NormX * (TerrainResolution - 1)), 0, TerrainResolution - 1);
const int32 TerrainY = FMath::Clamp(FMath::RoundToInt(NormY * (TerrainResolution - 1)), 0, TerrainResolution - 1);
const int32 TerrainIdx = TerrainY * TerrainResolution + TerrainX;

const bool bIsLand = (LandMask[TerrainIdx] != 0);
const float SurfaceElev = FinalElevation[TerrainIdx];
const bool bEligible = bIsLand && (SurfaceElev > Settings.MinSurfaceElevation);

for (int32 Z = 0; Z < CaveResZ; ++Z)
{
if (!bEligible)
{
// Solid everywhere — no caves in ocean or low-elevation areas
SetDensity(X, Y, Z, 1.0f);
continue;
}

// Depth fraction: 0 = surface, 1 = MaxCaveDepth below surface
const float DepthFrac = static_cast<float>(Z) / static_cast<float>(FMath::Max(CaveResZ - 1, 1));
const float DepthCm = DepthFrac * MaxDepthCm;

// World-space Z of this voxel (below surface)
const float SurfaceZ = SurfaceElev * MaxHeightCm;
const float VoxelZ = SurfaceZ - DepthCm;

// 3D noise sample coordinates (normalised world space scaled by CaveScale)
const float NoiseX = NormX * Settings.CaveScale;
const float NoiseY = NormY * Settings.CaveScale;
const float NoiseZ = (DepthFrac * Settings.MaxCaveDepthMeters / 100.0f) * Settings.CaveScale;

float CaveNoise = WorldNoise::FBM3D(NoiseX, NoiseY, NoiseZ,
Settings.CaveOctaves, Settings.CavePersistence, ActualSeed);

// Remap from [-1,1] to [0,1]
CaveNoise = (CaveNoise + 1.0f) * 0.5f;

// Fade caves near the surface to avoid holes in the terrain mesh
const float SurfaceFade = FMath::Clamp(DepthFrac * 4.0f, 0.0f, 1.0f);

// Fade caves near max depth to taper off smoothly
const float BottomFade = FMath::Clamp((1.0f - DepthFrac) * 4.0f, 0.0f, 1.0f);

// Density: positive = solid, negative = air
// If CaveNoise (after fade) exceeds threshold, mark as air
const float EffectiveNoise = CaveNoise * SurfaceFade * BottomFade;
const float Density = (EffectiveNoise > Settings.CaveThreshold)
? -(EffectiveNoise - Settings.CaveThreshold)
: 1.0f - EffectiveNoise;

SetDensity(X, Y, Z, Density);
}
}
}
}

//------------------------------------------------------------------------------
// ExtractMeshMarchingCubes
//------------------------------------------------------------------------------
void UCaveGenerator::ExtractMeshMarchingCubes(float WorldSizeCm, float MaxHeightCm,
const TArray<float>& FinalElevation)
{
CaveMesh = FCaveMeshData();

const float MaxDepthCm = Settings.MaxCaveDepthMeters * 100.0f;
const float CellSizeX = WorldSizeCm / static_cast<float>(FMath::Max(CaveResX - 1, 1));
const float CellSizeY = WorldSizeCm / static_cast<float>(FMath::Max(CaveResY - 1, 1));
const float CellSizeZ = MaxDepthCm / static_cast<float>(FMath::Max(CaveResZ - 1, 1));

const float IsoLevel = 0.0f;

// Vertex interpolation helper
auto InterpVertex = [&](int32 X1, int32 Y1, int32 Z1, int32 X2, int32 Y2, int32 Z2) -> FVector
{
const float D1 = GetDensity(X1, Y1, Z1);
const float D2 = GetDensity(X2, Y2, Z2);
const float T = (FMath::Abs(D2 - D1) > SMALL_NUMBER)
? FMath::Clamp((IsoLevel - D1) / (D2 - D1), 0.0f, 1.0f)
: 0.5f;

// Convert grid coords to world coords
auto GridToWorld = [&](int32 GX, int32 GY, int32 GZ) -> FVector
{
const float WorldX = GX * CellSizeX;
const float WorldY = GY * CellSizeY;

// Look up surface elevation for this XY column
const float NormGX = static_cast<float>(GX) / static_cast<float>(FMath::Max(CaveResX - 1, 1));
const float NormGY = static_cast<float>(GY) / static_cast<float>(FMath::Max(CaveResY - 1, 1));
const int32 TX = FMath::Clamp(FMath::RoundToInt(NormGX * (TerrainResolution - 1)), 0, TerrainResolution - 1);
const int32 TY = FMath::Clamp(FMath::RoundToInt(NormGY * (TerrainResolution - 1)), 0, TerrainResolution - 1);
const float SurfaceZ = FinalElevation[TY * TerrainResolution + TX] * MaxHeightCm;
const float WorldZ = SurfaceZ - static_cast<float>(GZ) * CellSizeZ;

return FVector(WorldX, WorldY, WorldZ);
};

const FVector P1 = GridToWorld(X1, Y1, Z1);
const FVector P2 = GridToWorld(X2, Y2, Z2);

return FMath::Lerp(P1, P2, T);
};

// Marching Cubes: iterate over all cells in the 3D grid
for (int32 Z = 0; Z < CaveResZ - 1; ++Z)
{
for (int32 Y = 0; Y < CaveResY - 1; ++Y)
{
for (int32 X = 0; X < CaveResX - 1; ++X)
{
// Read density at 8 cube corners
float Corners[8];
Corners[0] = GetDensity(X,     Y,     Z);
Corners[1] = GetDensity(X + 1, Y,     Z);
Corners[2] = GetDensity(X + 1, Y + 1, Z);
Corners[3] = GetDensity(X,     Y + 1, Z);
Corners[4] = GetDensity(X,     Y,     Z + 1);
Corners[5] = GetDensity(X + 1, Y,     Z + 1);
Corners[6] = GetDensity(X + 1, Y + 1, Z + 1);
Corners[7] = GetDensity(X,     Y + 1, Z + 1);

// Compute cube index from corner sign
int32 CubeIndex = 0;
for (int32 i = 0; i < 8; ++i)
{
if (Corners[i] < IsoLevel)
{
CubeIndex |= (1 << i);
}
}

if (EdgeTable[CubeIndex] == 0)
{
continue;
}

// Compute interpolated vertex positions on active edges
FVector EdgeVertices[12];

if (EdgeTable[CubeIndex] & 1)    EdgeVertices[0]  = InterpVertex(X, Y, Z, X+1, Y, Z);
if (EdgeTable[CubeIndex] & 2)    EdgeVertices[1]  = InterpVertex(X+1, Y, Z, X+1, Y+1, Z);
if (EdgeTable[CubeIndex] & 4)    EdgeVertices[2]  = InterpVertex(X+1, Y+1, Z, X, Y+1, Z);
if (EdgeTable[CubeIndex] & 8)    EdgeVertices[3]  = InterpVertex(X, Y, Z, X, Y+1, Z);
if (EdgeTable[CubeIndex] & 16)   EdgeVertices[4]  = InterpVertex(X, Y, Z+1, X+1, Y, Z+1);
if (EdgeTable[CubeIndex] & 32)   EdgeVertices[5]  = InterpVertex(X+1, Y, Z+1, X+1, Y+1, Z+1);
if (EdgeTable[CubeIndex] & 64)   EdgeVertices[6]  = InterpVertex(X+1, Y+1, Z+1, X, Y+1, Z+1);
if (EdgeTable[CubeIndex] & 128)  EdgeVertices[7]  = InterpVertex(X, Y, Z+1, X, Y+1, Z+1);
if (EdgeTable[CubeIndex] & 256)  EdgeVertices[8]  = InterpVertex(X, Y, Z, X, Y, Z+1);
if (EdgeTable[CubeIndex] & 512)  EdgeVertices[9]  = InterpVertex(X+1, Y, Z, X+1, Y, Z+1);
if (EdgeTable[CubeIndex] & 1024) EdgeVertices[10] = InterpVertex(X+1, Y+1, Z, X+1, Y+1, Z+1);
if (EdgeTable[CubeIndex] & 2048) EdgeVertices[11] = InterpVertex(X, Y+1, Z, X, Y+1, Z+1);

// Emit triangles from TriTable
for (int32 i = 0; TriTable[CubeIndex][i] != -1; i += 3)
{
const int32 BaseIdx = CaveMesh.Vertices.Num();

for (int32 j = 0; j < 3; ++j)
{
const FVector& V = EdgeVertices[TriTable[CubeIndex][i + j]];
CaveMesh.Vertices.Add(V);
CaveMesh.UVs.Add(FVector2D(V.X / WorldSizeCm, V.Y / WorldSizeCm));
// Dark grey-brown color for cave walls
CaveMesh.VertexColors.Add(FColor(90, 80, 70, 255));
}

// Compute face normal
const FVector& V0 = CaveMesh.Vertices[BaseIdx];
const FVector& V1 = CaveMesh.Vertices[BaseIdx + 1];
const FVector& V2 = CaveMesh.Vertices[BaseIdx + 2];
FVector Normal = FVector::CrossProduct(V1 - V0, V2 - V0).GetSafeNormal();

// Flip normal to face inward (into the cave interior)
// Since caves are negative density, normals should point inward
Normal = -Normal;

CaveMesh.Normals.Add(Normal);
CaveMesh.Normals.Add(Normal);
CaveMesh.Normals.Add(Normal);

CaveMesh.Triangles.Add(BaseIdx);
CaveMesh.Triangles.Add(BaseIdx + 1);
CaveMesh.Triangles.Add(BaseIdx + 2);
}
}
}
}
}

//------------------------------------------------------------------------------
// BuildCavePresenceMap
//------------------------------------------------------------------------------
void UCaveGenerator::BuildCavePresenceMap()
{
const int32 TotalPixels = TerrainResolution * TerrainResolution;
CavePresenceMap.SetNumZeroed(TotalPixels);

if (!Settings.bEnabled || CaveResZ <= 0)
{
return;
}

const float InvResX = 1.0f / static_cast<float>(CaveResX);
const float InvResY = 1.0f / static_cast<float>(CaveResY);

for (int32 TY = 0; TY < TerrainResolution; ++TY)
{
for (int32 TX = 0; TX < TerrainResolution; ++TX)
{
const float NormX = static_cast<float>(TX) / static_cast<float>(TerrainResolution - 1);
const float NormY = static_cast<float>(TY) / static_cast<float>(TerrainResolution - 1);
const int32 CX = FMath::Clamp(FMath::RoundToInt(NormX * (CaveResX - 1)), 0, CaveResX - 1);
const int32 CY = FMath::Clamp(FMath::RoundToInt(NormY * (CaveResY - 1)), 0, CaveResY - 1);

int32 AirCount = 0;
for (int32 CZ = 0; CZ < CaveResZ; ++CZ)
{
if (GetDensity(CX, CY, CZ) < 0.0f)
{
++AirCount;
}
}

CavePresenceMap[TY * TerrainResolution + TX] =
static_cast<float>(AirCount) / static_cast<float>(CaveResZ);
}
}
}

